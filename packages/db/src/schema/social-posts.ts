import { pgTable, uuid, text, timestamp, varchar, jsonb, boolean, integer } from 'drizzle-orm/pg-core';

export const socialPosts = pgTable('social_posts', {
  id: uuid('id').primaryKey().defaultRandom(),
  tenantId: uuid('tenant_id').notNull(),
  agentId: uuid('agent_id').notNull(),
  socialAccountId: uuid('social_account_id'),
  transactionId: uuid('transaction_id'),
  postType: varchar('post_type', { length: 50 }).notNull(),
  platform: varchar('platform', { length: 30 }).notNull(),
  content: text('content').notNull(),
  contentVariations: jsonb('content_variations'),
  hashtags: jsonb('hashtags'),
  mediaAssetIds: jsonb('media_asset_ids'),
  scheduledAt: timestamp('scheduled_at', { withTimezone: true }),
  publishedAt: timestamp('published_at', { withTimezone: true }),
  platformPostId: varchar('platform_post_id', { length: 200 }),
  platformPostUrl: text('platform_post_url'),
  status: varchar('status', { length: 30 }).notNull().default('draft'),
  complianceStatus: varchar('compliance_status', { length: 30 }).default('pending'),
  complianceIssues: jsonb('compliance_issues'),
  complianceCheckedAt: timestamp('compliance_checked_at', { withTimezone: true }),
  approvedBy: uuid('approved_by'),
  approvedAt: timestamp('approved_at', { withTimezone: true }),
  rejectionReason: text('rejection_reason'),
  isAutoGenerated: boolean('is_auto_generated').default(false),
  generationPrompt: text('generation_prompt'),
  abTestGroup: varchar('ab_test_group', { length: 10 }),
  metadata: jsonb('metadata'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  deletedAt: timestamp('deleted_at', { withTimezone: true }),
});
